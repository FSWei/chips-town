#!/usr/bin/env node
/**
 * convert.js — Tiled JSON → 游戏 map-data.ts 转换脚本
 *
 * 逻辑：
 *   - ground 层：草地/马路等地面 tile
 *   - objects 层：建筑/树等遮挡物
 *   - tile 属性 walkable=true → 可走
 *   - 未设置 walkable → 不可走（默认不可走）
 *   - 空格子（index=-1）→ 可走
 *
 * 用法: node map/scripts/convert.js [input.json] [output.ts]
 */

const fs = require('fs')
const path = require('path')

const INPUT = process.argv[2] || path.join(__dirname, '..', 'maps', 'town.json')
const OUTPUT = process.argv[3] || path.join(__dirname, '..', '..', 'client', 'src', 'game', 'map-data.ts')

// Parse Tiled JSON
const tiled = JSON.parse(fs.readFileSync(INPUT, 'utf-8'))
const mapW = tiled.width
const mapH = tiled.height
const tileW = tiled.tilewidth
const tileH = tiled.tileheight
const layers = tiled.layers

console.log(`[convert] Map: ${mapW}×${mapH}, tile: ${tileW}×${tileH}`)
console.log(`[convert] Layers: ${layers.map(l => l.name).join(', ')}`)

// Build walkable/blocked lookup from tileset tile properties
const walkableTiles = new Set()
const blockedTiles = new Set()
for (const ts of (tiled.tilesets || [])) {
  const firstgid = ts.firstgid || 1
  for (const tile of (ts.tiles || [])) {
    const props = {}
    for (const p of (tile.properties || [])) {
      props[p.name] = p.value
    }
    if (props.walkable === true || props.walkable === 'true') {
      walkableTiles.add(tile.id)
    }
    if (props.walkable === false || props.walkable === 'false' ||
        props.blocked === true || props.blocked === 'true') {
      blockedTiles.add(tile.id)
    }
  }
}

console.log(`[convert] Walkable tiles (from tileset properties): ${walkableTiles.size}`)
if (walkableTiles.size > 0) {
  console.log(`[convert] Walkable tile IDs: [${[...walkableTiles].sort((a,b)=>a-b).join(', ')}]`)
}

// Parse layers
const groundData = []
const objectData = []
const overlayData = []

for (const layer of layers) {
  if (layer.type !== 'tilelayer') continue

  let data
  if (Array.isArray(layer.data)) {
    data = layer.data
  } else if (typeof layer.data === 'string') {
    const buf = Buffer.from(layer.data, 'base64')
    data = []
    for (let i = 0; i < buf.length; i += 4) {
      data.push(buf.readUInt32LE(i))
    }
  }

  const firstgid = tiled.tilesets?.[0]?.firstgid || 1
  const converted = data.map(gid => gid === 0 ? -1 : gid - firstgid)

  const grid = []
  for (let y = 0; y < mapH; y++) {
    grid[y] = converted.slice(y * mapW, (y + 1) * mapW)
  }

  if (layer.name === 'ground') groundData.push(...grid)
  else if (layer.name === 'objects') objectData.push(...grid)
  else if (layer.name === 'overlay') overlayData.push(...grid)
}

// Generate collision data:
// 优先级：tile 属性 walkable（高） > 图层默认（低）
//   ground 层默认 = 可走, objects 层默认 = 不可走
//   tile 设了 walkable=On → 强制可走（即使在 objects 层）
//   tile 设了 walkable=Off → 强制不可走（即使在 ground 层）
//   没设 → 用图层默认
const collisionData = []
for (let y = 0; y < mapH; y++) {
  collisionData[y] = []
  for (let x = 0; x < mapW; x++) {
    const objIdx = objectData[y]?.[x] ?? -1
    const gndIdx = groundData[y]?.[x] ?? -1
    const ovIdx = overlayData[y]?.[x] ?? -1

    if (objIdx < 0 && gndIdx < 0 && ovIdx < 0) {
      // 空格子 → 可走
      collisionData[y][x] = 0
      continue
    }

    // 优先检查 tile 属性（高优先级）
    const activeIdx = ovIdx >= 0 ? ovIdx : objIdx >= 0 ? objIdx : gndIdx
    if (walkableTiles.has(activeIdx)) {
      collisionData[y][x] = 0  // tile 标了 walkable → 可走
      continue
    }
    if (blockedTiles.has(activeIdx)) {
      collisionData[y][x] = 1  // tile 标了 blocked → 不可走
      continue
    }

    // 没标属性 → 用图层默认（低优先级）
    // overlay 层默认不可走（跟 objects 一样）
    collisionData[y][x] = (objIdx >= 0 || ovIdx >= 0) ? 1 : 0
  }
}

// Stats
let groundFilled = 0, objectFilled = 0, overlayFilled = 0, blocked = 0, walkable = 0
for (let y = 0; y < mapH; y++) {
  for (let x = 0; x < mapW; x++) {
    if (groundData[y]?.[x] >= 0) groundFilled++
    if (objectData[y]?.[x] >= 0) objectFilled++
    if (overlayData[y]?.[x] >= 0) overlayFilled++
    if (collisionData[y][x] === 1) blocked++
    else walkable++
  }
}

// Generate TypeScript output
const ts = `// Auto-generated by map/scripts/convert.js — DO NOT EDIT
// Source: ${path.basename(INPUT)}
// Generated: ${new Date().toISOString()}

export const MAP_WIDTH = ${mapW}
export const MAP_HEIGHT = ${mapH}
export const TILE_SIZE = ${tileW}

// Ground layer: CleanCity tile indices, -1 = empty
export const GROUND_DATA: number[][] = ${JSON.stringify(groundData)}

// Object layer: CleanCity tile indices, -1 = empty
export const OBJECT_DATA: number[][] = ${JSON.stringify(objectData)}

// Overlay layer: rendered above objects (street lamps, signs), -1 = empty
export const OVERLAY_DATA: number[][] = ${JSON.stringify(overlayData)}

// Collision layer: 0 = walkable, 1 = blocked
export const COLLISION_DATA: number[][] = ${JSON.stringify(collisionData)}

// Combined map data (objects override ground)
export const MAP_DATA: number[][] = (() => {
  const merged: number[][] = []
  for (let y = 0; y < MAP_HEIGHT; y++) {
    merged[y] = []
    for (let x = 0; x < MAP_WIDTH; x++) {
      merged[y][x] = OBJECT_DATA[y]?.[x] >= 0 ? OBJECT_DATA[y][x] : (GROUND_DATA[y]?.[x] ?? -1)
    }
  }
  return merged
})()

// Walkable check: uses COLLISION_DATA, fallback to tile-based check
export function isWalkable(tileX: number, tileY: number): boolean {
  if (tileX < 0 || tileX >= MAP_WIDTH || tileY < 0 || tileY >= MAP_HEIGHT) return false
  return COLLISION_DATA[tileY]?.[tileX] === 0
}
`

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
fs.writeFileSync(OUTPUT, ts)

console.log(`\n[convert] Output: ${OUTPUT}`)
console.log(`[convert] Stats:`)
console.log(`  Ground tiles:  ${groundFilled}`)
console.log(`  Object tiles:  ${objectFilled}`)
console.log(`  Overlay tiles: ${overlayFilled}`)
console.log(`  Walkable cells: ${walkable}`)
console.log(`  Blocked cells:  ${blocked}`)
